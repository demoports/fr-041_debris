const hex = bytes => Array.from(bytes, byte => byte.toString(16).padStart(2, '0')).join('');
const block = new Uint8Array(64);
const setPixel = (index, red, green, blue, alpha) => {
  const offset = index * 4;
  block[offset] = blue;
  block[offset + 1] = green;
  block[offset + 2] = red;
  block[offset + 3] = alpha;
};
const assertBlock = (name, expected) => {
  assert.equal(hex(compressDxt5Block(block)), expected, `${name} matches vendored rygdxt`);
};

