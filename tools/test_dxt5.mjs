const sizedGenerators = new Set([0x21, 0x22, 0x32, 0x34, 0x3d]);
const dimensionMemo = new Map();
function bitmapDimensions(operationId) {
  if (dimensionMemo.has(operationId)) return dimensionMemo.get(operationId);
  const operation = document.operations[operationId];
  if (sizedGenerators.has(operation.classId)) {
    const result = [1 << (operation.parameters[0] & 0x7f), 1 << (operation.parameters[1] & 0x7f)];
    dimensionMemo.set(operationId, result);
    return result;
  }
  const inputDimensions = operation.inputs
    .filter(input => CLASS_REGISTRY[document.operations[input].classId]?.outputClass === 'KC_BITMAP')
    .map(bitmapDimensions).filter(Boolean);
  const result = inputDimensions[0] || null;
  for (const dimensions of inputDimensions.slice(1)) assert.deepEqual(dimensions, result,
    `bitmap op ${operationId} inputs retain matching dimensions`);
  dimensionMemo.set(operationId, result);
  return result;
}
assert.deepEqual(format9.map(operation => bitmapDimensions(operation.inputs[0])),
  new Array(5).fill(null).map(() => [512, 512]));

