// JS Bitmap storage is logical RGBA, whereas rygdxt's Pixel union is BGRA.
// A pure-red source catches an accidental first/third-channel gather swap.
const redWords = new Uint16Array(4 * 4 * 4);
for (let offset = 0; offset < redWords.length; offset += 4) {
  redWords[offset] = 0x7fff;
  redWords[offset + 3] = 0x7fff;
}
const redLevels = [];
forEachDxt5Mip({ ...mipBitmap, data: redWords }, 'rgba8',
  (level, width, height, bytes) => redLevels.push({ level, width, height, bytes: Array.from(bytes) }));
assert.deepEqual(redLevels.map(({ level, width, height }) => [level, width, height]),
  [[0, 4, 4], [1, 2, 2], [2, 1, 1]]);
for (const level of redLevels) {
  for (let offset = 0; offset < level.bytes.length; offset += 4) {
    assert.deepEqual(level.bytes.slice(offset, offset + 4), [255, 0, 0, 255]);
  }
}

