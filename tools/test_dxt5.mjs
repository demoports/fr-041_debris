function write16(bytes, offset, value) {
  bytes[offset] = value & 255;
  bytes[offset + 1] = value >>> 8;
}

function packIndices(bytes, offset, width, indices) {
  for (let index = 0; index < indices.length; index++) {
    for (let bit = 0; bit < width; bit++) {
      if (indices[index] & (1 << bit)) {
        const destination = index * width + bit;
        bytes[offset + (destination >> 3)] |= 1 << (destination & 7);
      }
    }
  }
}

// BC3 always uses the opaque four-color RGB palette. Its alpha half has two
// endpoint-order modes; lock all indices for both modes independently.
const handBlock = new Uint8Array(16);
handBlock[0] = 255;
handBlock[1] = 0;
packIndices(handBlock, 2, 3, Array.from({ length: 16 }, (_, index) => index & 7));
write16(handBlock, 8, 0xf800); // red
write16(handBlock, 10, 0x001f); // blue
packIndices(handBlock, 12, 2, Array.from({ length: 16 }, (_, index) => index & 3));
let decoded = decodeDxt5Block(handBlock);
assert.deepEqual(Array.from(decoded.slice(0, 16)), [
  255, 0, 0, 255,
  0, 0, 255, 0,
  170, 0, 85, 219,
  85, 0, 170, 182,
]);
assert.deepEqual(Array.from(decoded).filter((_, index) => (index & 3) === 3).slice(0, 8),
  [255, 0, 219, 182, 146, 109, 73, 36]);

handBlock.fill(0);
handBlock[0] = 0;
handBlock[1] = 255;
packIndices(handBlock, 2, 3, Array.from({ length: 16 }, (_, index) => index & 7));
write16(handBlock, 8, 0x001f); // endpoint0 blue is numerically below red
write16(handBlock, 10, 0xf800);
packIndices(handBlock, 12, 2, new Array(16).fill(3));
decoded = decodeDxt5Block(handBlock);
assert.deepEqual(Array.from(decoded.slice(0, 4)), [170, 0, 85, 0],
  'BC3 endpoint order never selects BC1 transparent black');
assert.deepEqual(Array.from(decoded).filter((_, index) => (index & 3) === 3).slice(0, 8),
  [0, 255, 51, 102, 153, 204, 0, 255]);

